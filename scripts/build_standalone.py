#!/usr/bin/env python3
"""Inline styles, seed data and app code into standalone.html (single self-contained file).

Used for the hosted demo link (htmlpreview.github.io renders a single HTML file from the repo).
Run after scripts/seed.py:  python3 scripts/build_standalone.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return f.read()


html = read("index.html")
css, seed, app = read("assets/styles.css"), read("data/seed.js"), read("assets/app.js")
for name, body in (("seed.js", seed), ("app.js", app)):
    assert "</script" not in body.lower(), name
html = html.replace('<link rel="stylesheet" href="assets/styles.css">', "<style>\n" + css + "\n</style>")
html = html.replace('<script src="data/seed.js"></script>', "<script>\n" + seed + "</script>")
html = html.replace('<script src="assets/app.js"></script>', "<script>\n" + app + "</script>")
assert 'src="' not in html.split("<body>")[1].replace('src="data:', ""), "unresolved external script"
with open(os.path.join(ROOT, "standalone.html"), "w", encoding="utf-8") as f:
    f.write("<!-- Generated by scripts/build_standalone.py. Unofficial demo built with Devin - synthetic data. -->\n" + html)
print("wrote standalone.html", len(html), "bytes")
