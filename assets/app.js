    const stepX = Math.ceil(maxX / 8);
    for (let v = 0; v <= maxX; v += stepX) grid += `<text x="${x(v)}" y="${Hh - 8}" font-size="10" text-anchor="middle" fill="#94a3b8">${v * 2}h</text>`;
