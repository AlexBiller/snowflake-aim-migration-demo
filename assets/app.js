    const maxX = Math.max(12, H[H.length - 1].tick + (allMerged() ? 0 : 4)); const maxY = MODS.length;
    const x = (v) => L + (v / maxX) * (W - L - R), y = (v) => T + (1 - v / maxY) * (Hh - T - B);
    const path = (k) => H.map((h, i) => `${i ? "L" : "M"}${x(h.tick).toFixed(1)},${y(h[k]).toFixed(1)}`).join("");
